# ── Численные противоречия: срабатывания ─────────────────────────────────────

@pytest.mark.parametrize("lines,pair", [
    # срок в разных формулировках одной темы (глагол vs отглагольное существительное)
    (("Срок рассмотрения жалобы клиента — 10 рабочих дней.",
      "Жалоба клиента рассматривается в течение 15 рабочих дней."), [1, 2]),
    # таблица (первая ячейка + заголовок столбца) против текста; другой тариф в таблице — не участвует
    (("| Тариф | Абонентская плата в месяц |", "|---|---|", "| «Старт» | 2 000 ₸ |", "| «Бизнес» | 9 000 ₸ |",
      "Абонентская плата по тарифу «Бизнес» составляет 7 500 ₸ в месяц."), [4, 5]),
    # проценты, слова в другом порядке
    (("Кешбэк по категории «Путешествия» — 5% от суммы покупки.",
      "Начисляется кешбэк 3% за покупки в категории «Путешествия»."), [1, 2]),
    # минуты
    (("Ссылка для восстановления пароля действует 15 минут.",
      "Срок действия ссылки восстановления пароля — 60 минут."), [1, 2]),
    # одна и та же верхняя граница на операцию сформулирована по-разному
    (("Сумма одного перевода по номеру телефона не превышает 1 000 000 ₸.",
      "Максимум для одного перевода по номеру телефона — 500 000 ₸."), [1, 2]),
    # нотация T+N = N рабочих дней
    (("Возмещение мерчанту перечисляется по схеме T+2.",
      "Перечисление возмещения мерчанту выполняется в течение 1 рабочего дня."), [1, 2]),
    # порог в условии с двух сторон: «если превышает X» и «если не превышает Y» при X > Y
    (("Если остаток на бонусном счёте превышает 50 000 ₸, клиент получает повышенную ставку.",
      "Повышенная ставка не начисляется, если остаток на бонусном счёте не превышает 30 000 ₸."), [1, 2]),
])
def test_value_conflicts_found(lines, pair):
    assert pair in value_pairs(*lines)


def test_value_conflict_finding_shape():
    fs = rules.scan_value_conflicts(doc("Ссылка для восстановления пароля действует 15 минут.",
                                        "Срок действия ссылки восстановления пароля — 60 минут."))
    f = fs[0]
    assert f.category == Category.contradiction and f.control_id == "CP-VALUE"
    assert 0.55 <= f.confidence <= 0.7 and len(f.evidence) == 2 and "?" in f.question


