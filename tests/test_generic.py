# ── Полярность: срабатывания ─────────────────────────────────────────────────

@pytest.mark.parametrize("lines", [
    # запрет vs разрешение
    ("Досрочное погашение кредита в первые 6 месяцев запрещено.",
     "Заёмщик вправе досрочно погасить кредит в любой момент без штрафа."),
    # фиксировано vs пересматривается
    ("Тарифы за обслуживание счёта фиксируются на весь срок действия договора.",
     "Банк пересматривает тарифы за обслуживание счёта ежеквартально."),
    # только с согласия vs автоматически
    ("Подключение платных уведомлений выполняется только с согласия клиента.",
     "Платные уведомления подключаются автоматически при выпуске карты."),
    # безотзывно vs можно отменить
    ("Платёж по QR после подтверждения клиентом является безотзывным.",
     "Клиент вправе отменить платёж по QR в течение 30 минут после подтверждения."),
    # до завершения проверки нельзя vs можно на время проверки
    ("До завершения верификации документов вывод средств на карту не выполняется.",
     "Пока верификация документов не завершена, клиент может выводить средства на карту до 20 000 ₸ в сутки."),
    # ограничение в таблице продуктов vs разрешение в тексте
    ("| Продукт | Условия |", "|---|---|", "| «Копилка» | без права досрочного снятия |",
     "Со вклада «Копилка» клиент может досрочно снять средства с потерей процентов."),
    # «нельзя» и разные события («после отправки» vs «до исполнения» — окно между ними противоречиво)
    ("Заявку на вывод после отправки в банк отменить нельзя.",
     "Клиент может отменить заявку на вывод в любой момент до её исполнения банком."),
])
def test_polarity_conflicts_found(lines):
    pairs = polarity_pairs(*lines)
    n = len(lines)
    assert pairs and pairs[0][1] == n and pairs[0][0] in (1, n - 1)


def test_polarity_reaches_semantic_scan_with_metadata():
    fs = rules.scan_semantic_conflicts(doc("Тарифы за обслуживание счёта фиксируются на весь срок действия договора.",
                                           "Банк пересматривает тарифы за обслуживание счёта ежеквартально."))
    assert [f.control_id for f in fs] == ["CP-POLARITY"]
    cp = CONFLICT_PAIRS_BY_ID["CP-POLARITY"]
    assert 2 <= len(cp.answer_options) <= 3 and cp.addressee and cp.default_assumption


