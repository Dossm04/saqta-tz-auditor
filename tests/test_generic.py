def doc(*lines: str):
    return load_text("\n".join(lines))


def value_pairs(*lines: str) -> list[list[int]]:
    return [f.lines for f in rules.scan_value_conflicts(doc(*lines))]


def polarity_pairs(*lines: str) -> list[list[int]]:
    return [f.lines for f in rules.scan_polarity_conflicts(doc(*lines))]


def ap_ids(*lines: str) -> set[str]:
    return {f.control_id for f in rules.scan_antipatterns(doc(*lines))}


def tbd_lines(*lines: str) -> set[int]:
    return {n for f in rules.scan_vague(doc(*lines)) if f.title.startswith("Открытый вопрос") for n in f.lines}


def vague_lines(*lines: str) -> set[int]:
    return {n for f in rules.scan_vague(doc(*lines)) for n in f.lines}


