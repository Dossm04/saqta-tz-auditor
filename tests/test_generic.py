@pytest.mark.parametrize("a,b", [
    ("хранится", "хранение"), ("пролонгируется", "пролонгация"), ("котировки", "котировка"),
    ("снятия", "снятие"), ("максимальная", "максимум"), ("переводов", "перевод"),
])
def test_stem_unifies_word_forms(a, b):
    assert rules.stem(a) == rules.stem(b)


def test_content_stems_drop_service_words_and_keep_acronyms():
    stems = rules.content_stems("Система должна проверять KYB продавца в течение суток")
