    recommendation: str
    answer_options: tuple[str, ...]
    addressee: str = "Бизнес-заказчик"
    default_assumption: str = ""
    topics: tuple[tuple[str, str], ...] = ()
    unless_a: str | None = None
    unless_b: str | None = None
    severity: str = "major"
    check_segments: bool = True            # не сравнивать строки про разные сегменты клиентов


